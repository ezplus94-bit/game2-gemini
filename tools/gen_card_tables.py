"""Builds the card tables in README.md from the card definitions, so the docs can never drift from the code.

    python tools/gen_card_tables.py            # print the tables
    python tools/gen_card_tables.py --write    # update the section between the markers in README.md
    python tools/gen_card_tables.py --check    # exit 1 if README.md is out of date (the test-suite does this too)
"""

