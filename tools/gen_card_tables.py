    out += _table(psup)
    pevs = sorted(event_cards(["Plunder"]), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Plunder Events ({len(pevs)}, bought with a Buy instead of gained; Events, Landmarks, Projects, Ways and Traits together: at most two per game)", ""]
    out += _table(pevs)
    pro_ev = sorted(event_cards(["Promos"]), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Promos Events ({len(pro_ev)}, bought with a Buy instead of gained)", ""]
    out += _table(pro_ev)
    rsev = sorted(event_cards(["Rising Sun"]), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Rising Sun Events ({len(rsev)}, bought with a Buy; Continue costs only Debt)", ""]
    out += _table(rsev)
    prophecies = sorted(prophecy_cards(), key=lambda n: n)
    out += ["", f"### Rising Sun Prophecies ({len(prophecies)}, one is used whenever an Omen is in the Kingdom; its rule starts when the last Sun token is removed)", ""]
    out += [f"* **{n}:** {_cell(get_card(n).text)}" for n in prophecies]
    ptraits = sorted(trait_cards(), key=lambda n: n)
    out += ["", f"### Plunder Traits ({len(ptraits)}, each lies on one random Action or Treasure Kingdom pile for the whole game)", ""]
