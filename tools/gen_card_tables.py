START = "<!-- CARD TABLES START (generated by tools/gen_card_tables.py: do not edit by hand) -->"
END = "<!-- CARD TABLES END -->"
README = ROOT / "README.md"
BASIC = ["Copper", "Silver", "Gold", "Platinum", "Potion", "Estate", "Duchy", "Province", "Colony", "Curse"]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _types(card) -> str:
    return " - ".join(sorted(t.value.capitalize() for t in card.types))


def _cost(card) -> str:
    """$4, $3P (a Potion), 8D (only Debt) or $5 + 3D."""
    coin = f"${card.cost}" + ("P" if card.potion_cost else "")
    if card.debt_cost:
        return f"{coin} + {card.debt_cost}D" if (card.cost or card.potion_cost) else f"{card.debt_cost}D"
    return coin


def _table(names: list) -> list:
    lines = ["| Card | Cost | Type | Effect |", "|---|---|---|---|"]
    for name in names:
        card = get_card(name)
        lines.append(f"| **{name}** | {_cost(card)} | {_types(card)} | {_cell(card.text)} |")
    return lines


def _glance(names: list) -> str:
    return ", ".join(f"{n} ({_cost(get_card(n))})" for n in names)


