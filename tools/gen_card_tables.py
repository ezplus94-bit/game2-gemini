"""Builds the card tables in README.md from the card definitions, so the docs can never drift from the code.

    python tools/gen_card_tables.py            # print the tables
    python tools/gen_card_tables.py --write    # update the section between the markers in README.md
    python tools/gen_card_tables.py --check    # exit 1 if README.md is out of date (the test-suite does this too)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dominion.cards import expansions, get_card, kingdom_cards  # noqa: E402
from dominion.cards.registry import catastrophe_cards, companion_cards, special_cards  # noqa: E402

START = "<!-- CARD TABLES START (generated by tools/gen_card_tables.py: do not edit by hand) -->"
END = "<!-- CARD TABLES END -->"
README = ROOT / "README.md"
BASIC = ["Copper", "Silver", "Gold", "Platinum", "Potion", "Estate", "Duchy", "Province", "Colony", "Curse"]


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _types(card) -> str:
    return " - ".join(sorted(t.value.capitalize() for t in card.types))


def _table(names: list) -> list:
    lines = ["| Card | Cost | Type | Effect |", "|---|---|---|---|"]
    for name in names:
        card = get_card(name)
        lines.append(f"| **{name}** | ${card.cost} | {_types(card)} | {_cell(card.text)} |")
    return lines


def _glance(names: list) -> str:
    return ", ".join(f"{n} (${get_card(n).cost})" for n in names)


def render_tables() -> str:
    groups = [("Basic cards", BASIC)]
    for exp in expansions():
        groups.append((f"{exp} Kingdom cards", sorted(kingdom_cards([exp]), key=lambda n: (get_card(n).cost, n))))
    groups.append(("Catastrophe cards", sorted(catastrophe_cards(), key=lambda n: (get_card(n).cost, n))))
    groups.append(("Special cards", sorted(special_cards(), key=lambda n: (get_card(n).cost, n))))
    groups.append(("Exodia pieces", sorted(companion_cards(), key=lambda n: (get_card(n).cost, n))))
    total = sum(len(names) for _title, names in groups)
    out = [f"### All {total} cards at a glance", ""]
    out += [f"* **{title} ({len(names)}):** {_glance(names)}" for title, names in groups]
    out += ["", "### Basic cards", ""]
    out += _table(BASIC)
    for exp in expansions():
        names = sorted(kingdom_cards([exp]), key=lambda n: (get_card(n).cost, n))
        out += ["", f"### {exp} Kingdom cards ({len(names)})", ""]
        out += _table(names)
    cats = sorted(catastrophe_cards(), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Catastrophe cards ({len(cats)}, optional house rule: they hurt)", ""]
    out += _table(cats)
    specials = sorted(special_cards(), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Special cards ({len(specials)}, optional house rule: they help)", ""]
    out += _table(specials)
    limbs = sorted(companion_cards(), key=lambda n: (get_card(n).cost, n))
    out += ["", f"### Exodia pieces ({len(limbs)}, they arrive together with Exodia the Forbidden One)", ""]
    out += _table(limbs)
    return "\n".join(out)


def updated_readme(text: str) -> str:
    if START not in text or END not in text:
        raise SystemExit("README.md has no card-table markers.")
    head, rest = text.split(START, 1)
    _old, tail = rest.split(END, 1)
    return head + START + "\n\n" + render_tables() + "\n\n" + END + tail


def main(argv: list) -> int:
    if "--write" in argv:
        README.write_text(updated_readme(README.read_text(encoding="utf-8")), encoding="utf-8")
        print("README.md updated.")
        return 0
    if "--check" in argv:
        if README.read_text(encoding="utf-8") != updated_readme(README.read_text(encoding="utf-8")):
            print("README.md card tables are out of date: run  python tools/gen_card_tables.py --write")
            return 1
        print("README.md card tables are up to date.")
        return 0
    print(render_tables())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
